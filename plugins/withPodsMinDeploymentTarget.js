const { withDangerousMod } = require('@expo/config-plugins');
const fs = require('fs');
const path = require('path');

/**
 * Xcode 27 (installed on this Mac Oct 14 2026, after build 244 shipped) turns
 * an old pod deployment target into a hard error:
 *
 *   The iOS deployment target 'IPHONEOS_DEPLOYMENT_TARGET' is set to 13.0,
 *   but the range of supported deployment target versions is 15.0 to 27.0.x.
 *
 * Stripe, PostHog, Sentry, SDWebImage, RNSVG, RNDeviceInfo and
 * ReachabilitySwift still declare 9.0 to 13.0, so the archive failed before
 * compiling a single file (Oct 25 2026, test build 258e4e5). The app itself
 * targets 15.1, so lifting every pod below it to 15.1 changes nothing on the
 * devices we support. Injected after react_native_post_install, like
 * withFmtConsteval, because the Podfile is regenerated by prebuild.
 */
const MIN_TARGET = '15.1';
const MARKER = '# withPodsMinDeploymentTarget';
const INJECT = `
    ${MARKER}: Xcode 27 rejects pod targets below 15.0, see plugins/withPodsMinDeploymentTarget.js.
    installer.pods_project.targets.each do |target|
      target.build_configurations.each do |config|
        current = config.build_settings['IPHONEOS_DEPLOYMENT_TARGET']
        if current.nil? || Gem::Version.new(current) < Gem::Version.new('${MIN_TARGET}')
          config.build_settings['IPHONEOS_DEPLOYMENT_TARGET'] = '${MIN_TARGET}'
        end
      end
    end
`;

module.exports = function withPodsMinDeploymentTarget(config) {
  return withDangerousMod(config, [
    'ios',
    (cfg) => {
      const podfile = path.join(cfg.modRequest.platformProjectRoot, 'Podfile');
      let src = fs.readFileSync(podfile, 'utf8');
      if (src.includes(MARKER)) return cfg;
      const re = /(post_install do \|installer\|\n[\s\S]*?react_native_post_install\([\s\S]*?\n\s*\)\n)/;
      if (!re.test(src)) {
        throw new Error(
          '[withPodsMinDeploymentTarget] react_native_post_install call not found in the Podfile'
        );
      }
      src = src.replace(re, `$1${INJECT}`);
      fs.writeFileSync(podfile, src);
      return cfg;
    },
  ]);
};
